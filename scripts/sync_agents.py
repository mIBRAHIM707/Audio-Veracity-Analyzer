"""Generate native adapters from shared role contracts; --check never writes."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def expected_files():
    common = (ROOT / "docs/agents/common.md").read_text(encoding="utf-8")
    catalog = json.loads((ROOT / "docs/agents/catalog.json").read_text(encoding="utf-8"))
    for role in catalog:
        slug = role["id"]
        body = (ROOT / role["role_file"]).read_text(encoding="utf-8")
        instructions = "Read AGENTS.md first.\n\n" + common + "\n" + body
        codex = (
            "# Generated by scripts/sync_agents.py; edit docs/agents instead.\n"
            f'name = {json.dumps("ava_" + slug.replace("-", "_"))}\n'
            f'description = {json.dumps(role["description"])}\n'
        )
        if "model" in role:
            codex += f'model = {json.dumps(role["model"])}\n'
        # JSON basic string escaping is compatible with these TOML string contents.
        codex += "developer_instructions = " + json.dumps(instructions) + "\n"
        yield ROOT / f".codex/agents/ava-{slug}.toml", codex
        tools = "Read, Grep, Glob, Bash, Write, Edit"
        claude_body = instructions
        description = role["description"]
        if slug == "researcher":
            tools = "Read, Grep, Glob, WebFetch, WebSearch"
        elif slug == "coordinator":
            tools += ", Agent"
        elif slug == "test-designer":
            tools = "Read, Grep, Glob, Write"
            description = "Prepares a requirement-linked handoff to Codex GPT-6 Astra for test-case design; does not impersonate Astra."
            claude_body = (
                "Read AGENTS.md and docs/agents/common.md.\n\n"
                "You are the Claude-side test-design handoff coordinator. Claude's "
                "native model field cannot run GPT-6 Astra. Do not create a catalog "
                "and label it Astra-authored. Collect task, source revision, FR/ADR "
                "IDs, relevant code paths, acceptance criteria and unresolved "
                "questions into a per-task handoff. Ask the Codex ava_test_designer "
                "role to use gpt-6-astra and docs/agents/test-designer.md. If that "
                "model is unavailable, report the limitation. Claude may implement "
                "and execute the returned cases and report its actual provenance.\n"
            )
        claude = (
            f"---\nname: ava-{slug}\ndescription: {json.dumps(description)}\n"
            f"tools: {tools}\nmodel: inherit\n---\n\n"
            "<!-- Generated by scripts/sync_agents.py; edit docs/agents instead. -->\n\n"
            + claude_body
        )
        yield ROOT / f".claude/agents/ava-{slug}.md", claude


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    drift = []
    count = 0
    for path, content in expected_files():
        count += 1
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if drift:
        print("Agent adapter drift:\n" + "\n".join(drift))
        return 1
    print(f"Agent adapters {'checked' if args.check else 'generated'}: {count}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
